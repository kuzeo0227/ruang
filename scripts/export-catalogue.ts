// Validates the catalogue and writes docs/catalogue.csv (opens in Excel).
// Prints a per-style summary so price levels can be sanity-checked.

import { writeFileSync } from 'node:fs';
import { CATALOGUE } from '../src/catalogue/items';
import { MATERIALS } from '../src/catalogue/materials';
import { BANDS, SHARED_SOURCES } from '../src/catalogue/pricing';
import { STYLES, STYLE_ORDER } from '../src/catalogue/styles';

let problems = 0;
const problem = (msg: string) => {
  problems++;
  console.log(`  PROBLEM  ${msg}`);
};

const ids = new Set<string>();
for (const item of CATALOGUE) {
  if (ids.has(item.id)) problem(`duplicate id ${item.id}`);
  ids.add(item.id);
  if (!(item.priceMYR > 0)) problem(`${item.id} has no price`);
  if (!item.finishes.length) problem(`${item.id} has no finishes`);
  for (const f of item.finishes) if (!MATERIALS[f.material]) problem(`${item.id} unknown finish ${f.material}`);
  if (item.finishes[0]!.deltaMYR !== 0) problem(`${item.id} default finish should have zero delta`);
}

// Every style needs one piece in every style-driven category.
const styledCategories = [...new Set(CATALOGUE.filter((i) => i.styles.length === 1 && i.id.startsWith(i.styles[0]!)).map((i) => i.category))];
for (const s of STYLE_ORDER) {
  for (const c of styledCategories) {
    if (!CATALOGUE.some((i) => i.category === c && i.styles.includes(s))) problem(`${s} has no ${c}`);
  }
}

const csvCell = (v: unknown) => {
  const s = String(v ?? '');
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
const header = ['id', 'name', 'brand', 'category', 'styles', 'rooms', 'width_mm', 'depth_mm', 'height_mm', 'mount', 'price_myr', 'finishes', 'variants', 'model', 'price_basis', 'description'];
const rows = CATALOGUE.map((i) => [
  i.id,
  i.name,
  i.brand,
  i.category,
  i.styles.map((s) => STYLES[s].name).join(' / '),
  i.rooms.join(' / '),
  i.size.w,
  i.size.d,
  i.size.h,
  i.mount,
  i.priceMYR,
  i.finishes.map((f) => `${MATERIALS[f.material].name}${f.deltaMYR ? ` (${f.deltaMYR > 0 ? '+' : ''}RM${f.deltaMYR})` : ''}`).join(' / '),
  (i.variants ?? []).map((v) => `${v.label} RM${v.priceMYR}`).join(' / '),
  i.model.kind === 'polyhaven' ? `Poly Haven: ${i.model.id}` : `Parametric: ${i.model.generator}`,
  i.priceBasis,
  i.description,
]);
writeFileSync(new URL('../docs/catalogue.csv', import.meta.url), '﻿' + [header, ...rows].map((r) => r.map(csvCell).join(',')).join('\n') + '\n');

const money = (n: number) => `RM${n.toLocaleString('en-MY')}`;
const link = (note: string, url?: string) => (url ? `[${note}](${url})` : note);
const bandRows = Object.entries(BANDS).map(([cat, band]) => {
  const cell = (tier: 'budget' | 'mid' | 'premium') => {
    const r = band!.refs.find((x) => x.tier === tier)!;
    return `**${money(r.myr)}**${r.derived ? ' *(derived)*' : ''}<br>${link(r.note, r.url)}`;
  };
  return `| ${cat} | ${cell('budget')} | ${cell('mid')} | ${cell('premium')} |`;
});
const styleRows = STYLE_ORDER.map((s) => `| ${STYLES[s].name} | ${STYLES[s].brand} | ${STYLES[s].tier.toFixed(2)} |`);
const sharedRows = Object.entries(SHARED_SOURCES).map(([k, v]) => `| ${k} | ${link(v.note, 'url' in v ? v.url : undefined)} |`);
writeFileSync(
  new URL('../docs/pricing.md', import.meta.url),
  `# How catalogue prices are set

All products in Ruang are invented. Their prices are dummy values placed where comparable
products actually sell in Malaysia, based on online retail listings accessed on 23 October 2026.
Renovation costs are excluded. This file is generated by \`npm run export:catalogue\`.

## Method

1. For each furniture category, three reference prices were collected:
   **budget** = IKEA Malaysia median, **mid** = Fella Design (Malaysian brand) median,
   **premium** = BoConcept Malaysia recommended retail median.
2. Each style pack sits at a tier between 0 (budget) and 2 (premium).
3. An item's price is interpolated between the references on a log scale at its style's tier,
   then rounded to a retail-looking figure (RM2,449, RM899).
4. Shared items (appliances, sanitary ware, plants, lighting) quote one specific listing, or are marked as estimates.

| Style | Invented brand | Tier |
|---|---|---|
${styleRows.join('\n')}

## Category bands

| Category | Budget | Mid | Premium |
|---|---|---|---|
${bandRows.join('\n')}

## Shared items

| Source key | Reference |
|---|---|
${sharedRows.join('\n')}
`,
);

console.log(`${CATALOGUE.length} items written to docs/catalogue.csv, sources to docs/pricing.md`);
console.log(`  Poly Haven models: ${CATALOGUE.filter((i) => i.model.kind === 'polyhaven').length}, parametric: ${CATALOGUE.filter((i) => i.model.kind === 'parametric').length}`);
console.log('\nStyle pieces (one of each category), MYR:');
for (const s of STYLE_ORDER) {
  const own = CATALOGUE.filter((i) => i.styles.length === 1 && i.styles[0] === s);
  const sofa = own.find((i) => i.category === 'sofa')!;
  const bed = own.find((i) => i.category === 'bedQueen')!;
  const total = own.reduce((t, i) => t + i.priceMYR, 0);
  console.log(`  ${STYLES[s].name.padEnd(30)} tier ${STYLES[s].tier.toFixed(2)}  sofa RM${sofa.priceMYR.toLocaleString()}  queen bed RM${bed.priceMYR.toLocaleString()}  ${own.length} pieces RM${total.toLocaleString()}`);
}

if (problems) {
  console.log(`\n${problems} problem(s).`);
  process.exit(1);
}
